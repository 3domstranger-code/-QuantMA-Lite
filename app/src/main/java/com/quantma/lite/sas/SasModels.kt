package com.quantma.lite.sas

import java.util.UUID

/**
 * Secure Agent Shell (SAS) — Domain Models.
 *
 * Defines the structured protocol between LLM and the Android file system executor.
 * All tool interactions go through ToolCommand → ShellExecutor → ToolResponse.
 */

// ─── Tool Types ─────────────────────────────────────────────────────────────

/**
 * Enumeration of all available tools the LLM agent can invoke.
 */
enum class ToolType(val toolName: String) {
    READ_FILE("read_file"),
    WRITE_FILE("write_file"),
    CREATE_FILE("create_file"),
    APPEND_FILE("append_file"),
    LIST_DIR("list_dir"),
    SEARCH_GREP("search_grep"),
    GET_DIFF("get_diff"),
    GIT_STATUS("git_status"),
    GIT_ADD("git_add"),
    GIT_COMMIT("git_commit"),
    GIT_LOG("git_log"),
    GIT_BRANCH("git_branch"),

    // v3.1 — File Operations
    DELETE_FILE("delete_file"),

    // v3.1 — Code Quality (Group B)
    LINT_FILE("lint_file"),
    FORMAT_FILE("format_file"),
    COUNT_LINES("count_lines"),
    FIND_TODO("find_todo"),

    // v3.1 — Extended Git (Group A)
    GIT_STATUS_DETAILED("git_status_detailed"),
    GIT_COMMIT_AUTO("git_commit_auto"),
    GIT_PUSH_SAFE("git_push_safe"),
    GIT_STASH("git_stash"),

    // Branch / Merge operations
    GIT_CREATE_BRANCH("git_create_branch"),
    GIT_CHECKOUT("git_checkout"),
    GIT_DELETE_BRANCH("git_delete_branch"),
    GIT_MERGE("git_merge"),

    DONE("done");

    enum class Category(val label: String) {
        FILE_OPS("File Operations"),
        SEARCH("Search & Analysis"),
        GIT("Git"),
        CODE_QUALITY("Code Quality"),
        AGENT("Agent Control")
    }

    val category: Category get() = when (this) {
        READ_FILE, WRITE_FILE, CREATE_FILE, APPEND_FILE, LIST_DIR, DELETE_FILE -> Category.FILE_OPS
        SEARCH_GREP, GET_DIFF -> Category.SEARCH
        GIT_STATUS, GIT_ADD, GIT_COMMIT, GIT_LOG, GIT_BRANCH,
        GIT_STATUS_DETAILED, GIT_COMMIT_AUTO, GIT_PUSH_SAFE, GIT_STASH,
        GIT_CREATE_BRANCH, GIT_CHECKOUT, GIT_DELETE_BRANCH, GIT_MERGE -> Category.GIT
        LINT_FILE, FORMAT_FILE, COUNT_LINES, FIND_TODO -> Category.CODE_QUALITY
        DONE -> Category.AGENT
    }

    companion object {
        private val byName = entries.associateBy { it.toolName }

        fun fromName(name: String): ToolType? = byName[name.lowercase().trim()]
    }
}

// ─── Tool Command (LLM → Executor) ──────────────────────────────────────────

/**
 * A structured command generated by the LLM.
 *
 * JSON format:
 * ```json
 * {
 *   "id": "uuid",
 *   "tool": "read_file",
 *   "args": { "path": "src/main.kt" },
 *   "thought": "I need to read the file first"
 * }
 * ```
 */
data class ToolCommand(
    val id: String = UUID.randomUUID().toString(),
    val tool: ToolType,
    val args: Map<String, Any> = emptyMap(),
    val thought: String? = null
) {
    /** Convenience: get a string argument by key. */
    fun stringArg(key: String): String? = args[key]?.toString()

    /** Convenience: get a string argument or throw. */
    fun requireStringArg(key: String): String =
        stringArg(key) ?: throw IllegalArgumentException("Missing required argument: $key")

    /** Convenience: get an int argument with default. */
    fun intArg(key: String, default: Int): Int =
        (args[key] as? Number)?.toInt() ?: args[key]?.toString()?.toIntOrNull() ?: default

    /** Convenience: get a list of strings argument. */
    @Suppress("UNCHECKED_CAST")
    fun stringListArg(key: String): List<String> =
        (args[key] as? List<*>)?.mapNotNull { it?.toString() } ?: emptyList()
}

// ─── Tool Response (Executor → LLM / UI) ────────────────────────────────────

/**
 * Result of executing a ToolCommand.
 */
sealed class ToolResponse {
    /** Tool executed successfully. */
    data class Success(
        val output: String,
        val metadata: Map<String, Any> = emptyMap()
    ) : ToolResponse()

    /** Tool execution failed. */
    data class Error(
        val code: String,
        val message: String
    ) : ToolResponse()

    /**
     * Tool requires user approval before executing (write, create, append, git commit/add).
     * The UI layer should show a confirmation dialog with the description.
     */
    data class NeedsApproval(
        val description: String,
        val command: ToolCommand,
        val preview: String? = null
    ) : ToolResponse()

    /** Format response for feeding back to LLM context. */
    fun toLlmString(): String = when (this) {
        is Success -> output
        is Error -> "ERROR [$code]: $message"
        is NeedsApproval -> "PENDING_APPROVAL: $description"
    }
}

// ─── Supporting Models ──────────────────────────────────────────────────────

/**
 * A single match from search_grep tool.
 */
data class SearchMatch(
    val file: String,
    val line: Int,
    val content: String
) {
    override fun toString(): String = "$file:$line: $content"
}

/**
 * Statistics from a diff computation.
 */
data class DiffStats(
    val additions: Int,
    val deletions: Int
) {
    val total: Int get() = additions + deletions
    override fun toString(): String = "+$additions / -$deletions"
}

// ─── Sandbox Configuration ──────────────────────────────────────────────────

/**
 * Configuration for the SAS sandbox.
 * Controls security boundaries and resource limits.
 */
data class SasConfig(
    /** Root directory for all file operations. All paths are relative to this. */
    val workingDir: String,

    /** Allowed file extensions (without dot). Empty = allow all. */
    val allowedExtensions: Set<String> = DEFAULT_ALLOWED_EXTENSIONS,

    /** Maximum file size in bytes for read/write operations. */
    val maxFileSizeBytes: Long = DEFAULT_MAX_FILE_SIZE,

    /** Maximum directory depth relative to workingDir. */
    val maxPathDepth: Int = DEFAULT_MAX_DEPTH,

    /** Maximum number of search results from search_grep. */
    val maxSearchResults: Int = DEFAULT_MAX_SEARCH_RESULTS,

    /** Maximum number of entries returned by list_dir. */
    val maxListEntries: Int = DEFAULT_MAX_LIST_ENTRIES,

    /** Maximum lines to display when reading a file. */
    val maxDisplayLines: Int = DEFAULT_MAX_DISPLAY_LINES,

    /** Maximum characters in tool output. */
    val maxOutputChars: Int = DEFAULT_MAX_OUTPUT_CHARS,

    /** System paths that are always blocked. */
    val blockedPrefixes: List<String> = DEFAULT_BLOCKED_PREFIXES,

    /**
     * Maximum number of steps in a single plan.
     * Prevents memory exhaustion on low-end devices by limiting plan complexity.
     */
    val maxStepsPerPlan: Int = DEFAULT_MAX_STEPS_PER_PLAN,

    /**
     * Context token budget.
     * Adapt to model size: 7B → 1024, 13B → 2048, 30B+ → 4096.
     * Use [computeContextBudget] to derive from model parameter count.
     */
    val contextTokenBudget: Int = DEFAULT_CONTEXT_TOKEN_BUDGET,

    /**
     * Maximum number of tool calls per minute (rate limiting).
     * Protects against runaway LLM loops consuming device resources.
     * 0 = unlimited.
     */
    val maxOpsPerMinute: Int = DEFAULT_MAX_OPS_PER_MINUTE
) {
    companion object {
        val DEFAULT_ALLOWED_EXTENSIONS = setOf(
            "java", "kt", "kts", "cpp", "c", "h", "hpp",
            "py", "md", "txt", "xml", "gradle",
            "json", "yaml", "yml", "toml",
            "properties", "pro", "cfg", "gitignore",
            "sh", "bat", "rs", "go", "js", "ts",
            "html", "css", "scss", "svg"
        )

        val DEFAULT_BLOCKED_PREFIXES = listOf(
            "/system", "/data/data", "/proc", "/dev",
            "/etc", "/sbin", "/vendor"
        )

        const val DEFAULT_MAX_FILE_SIZE = 5L * 1024 * 1024  // 5 MB
        const val DEFAULT_MAX_DEPTH = 20
        const val DEFAULT_MAX_SEARCH_RESULTS = 50
        const val DEFAULT_MAX_LIST_ENTRIES = 50
        const val DEFAULT_MAX_DISPLAY_LINES = 100
        const val DEFAULT_MAX_OUTPUT_CHARS = 4000
        const val DEFAULT_MAX_STEPS_PER_PLAN = 10
        const val DEFAULT_CONTEXT_TOKEN_BUDGET = 1024
        const val DEFAULT_MAX_OPS_PER_MINUTE = 60

        /**
         * Derive a context budget appropriate for a model by parameter count.
         * Small models get tighter budgets to leave more room for generation.
         *
         * @param modelParamsBillions Approximate parameter count in billions (e.g. 7.0, 13.0, 32.0)
         * @return Recommended context token budget
         */
        fun computeContextBudget(modelParamsBillions: Float): Int = when {
            modelParamsBillions < 10f  -> 1024   // 7B
            modelParamsBillions < 20f  -> 2048   // 13B
            modelParamsBillions < 40f  -> 3072   // 30B
            else                       -> 4096   // 70B+
        }
    }
}

