/**
 * A snapshot of a file's state at a point in time.
 * Used by [FileHistoryManager] for undo/redo operations.
 */
data class FileSnapshot(
    /** Relative path from working directory. */
    val path: String,
    /** Timestamp when the snapshot was taken (millis). */
    val timestamp: Long = System.currentTimeMillis(),
    /** File content at snapshot time. Null if file didn't exist (creation snapshot). */
    val content: String?,
    /** File size in bytes at snapshot time. */
    val sizeBytes: Long = content?.toByteArray()?.size?.toLong() ?: 0L
)

// ─── Parsed LLM Output ─────────────────────────────────────────────────────

/**
 * Result of parsing LLM output in mixed mode.
 * LLM may produce text + JSON command in a single message.
 */
data class ParsedLlmOutput(
    /** Plain text portions (chat message to show user). Empty if output was pure JSON. */
    val textParts: List<String> = emptyList(),
    /** Parsed tool command, if found. Null if output was pure text. */
    val command: ToolCommand? = null,
    /** Whether the LLM signaled completion (DONE). */
    val isDone: Boolean = false
) {
    /** True if there is displayable text for the user. */
    val hasText: Boolean get() = textParts.isNotEmpty()
    /** True if a tool command was detected. */
    val hasCommand: Boolean get() = command != null
    /** Combined text output for display. */
    val displayText: String get() = textParts.joinToString("\n").trim()
}

// ─── Code Validation ────────────────────────────────────────────────────────

/**
 * Language detected from file extension.
 */
enum class CodeLanguage(val extensions: Set<String>) {
    KOTLIN(setOf("kt", "kts")),
    JAVA(setOf("java")),
    PYTHON(setOf("py")),
    CPP(setOf("cpp", "c", "h", "hpp")),
    JAVASCRIPT(setOf("js", "ts")),
    XML(setOf("xml")),
    RUST(setOf("rs")),
    GO(setOf("go")),
    UNKNOWN(emptySet());

    companion object {
        fun fromExtension(ext: String): CodeLanguage =
            entries.firstOrNull { ext.lowercase() in it.extensions } ?: UNKNOWN
    }
}

/**
 * Result of code validation before writing.
 */
data class ValidationResult(
    /** Whether the code passed all checks. */
    val valid: Boolean,
    /** List of issues found (empty if valid). */
    val errors: List<ValidationError> = emptyList(),
    /** List of warnings (non-blocking). */
    val warnings: List<String> = emptyList(),
    /** Auto-fixed content if fixes were applied. Null if no fixes needed or not fixable. */
    val autoFixed: String? = null
) {
    /** True if any error has CRITICAL severity (should block writes). */
    val hasCritical: Boolean get() = errors.any { it.severity == ValidationSeverity.CRITICAL }
}

/**
 * A specific validation error.
 */
data class ValidationError(
    val type: ValidationType,
    val message: String,
    val line: Int? = null,
    val severity: ValidationSeverity = ValidationSeverity.ERROR
)

enum class ValidationType {
    UNMATCHED_BRACKET,
    UNCLOSED_STRING,
    STRUCTURAL_REGRESSION,
    CONTENT_LOSS,
    ENCODING_ERROR,
    EMPTY_CONTENT
}

enum class ValidationSeverity {
    WARNING, ERROR, CRITICAL
}

// ─── Hook System (v3.1) ─────────────────────────────────────────────────────

/**
 * Type of hook: fires before or after the main tool execution.
 */
enum class HookType { PRE_COMMAND, POST_COMMAND }

/**
 * Configuration for an automatic hook.
 *
 * A hook is an internal SAS tool command that fires automatically
 * when a trigger tool executes. Hooks are SAS-internal only (not shell commands).
 *
 * Example: auto-format after every write to a Kotlin file
 * ```kotlin
 * HookConfig(
 *     hookType = HookType.POST_COMMAND,
 *     triggerTool = ToolType.WRITE_FILE,
 *     hookAction = ToolCommand(tool = ToolType.FORMAT_FILE, args = mapOf("path" to "\$TARGET_PATH")),
 *     description = "Auto-format Kotlin files after write",
 *     condition = HookCondition.PathExtension(setOf("kt", "kts"))
 * )
 * ```
 *
 * Placeholder `$TARGET_PATH` is resolved from the triggering command's `path` arg.
 */
data class HookConfig(
    val hookType: HookType,
    val triggerTool: ToolType,
    val hookAction: ToolCommand,
    val enabled: Boolean = true,
    val description: String = "",
    /**
     * Optional condition that must be true for the hook to fire.
     * Null = always fire (previous behavior, preserved for backward compatibility).
     */
    val condition: HookCondition? = null,
    /**
     * Execution priority. Lower number = runs first when multiple hooks match.
     * Default 0.
     */
    val priority: Int = 0
)

/**
 * Condition evaluated before a hook fires.
 * When the condition is not met, the hook is silently skipped.
 */
sealed class HookCondition {
    /**
     * Hook fires only if the trigger command's `path` argument has one of the
     * specified file extensions (without the dot).
     *
     * Example: `PathExtension(setOf("kt", "kts"))` fires only on Kotlin files.
     */
    data class PathExtension(val extensions: Set<String>) : HookCondition()

    /**
     * Hook fires only if the trigger command's `path` argument matches the given regex.
     *
     * Example: `PathPattern(Regex("src/.*\\.kt$"))` fires only for .kt files under src/.
     */
    data class PathPattern(val pattern: Regex) : HookCondition()

    /**
     * Hook fires only when a tool response SUCCESS output contains the given substring.
     * Useful for post-hooks that should only run when the tool output indicates an issue.
     *
     * Example: `OutputContains("WARNING")` fires only when the previous tool emitted a warning.
     */
    data class OutputContains(val substring: String, val ignoreCase: Boolean = true) : HookCondition()
}

