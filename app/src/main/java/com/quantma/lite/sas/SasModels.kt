// ─── Bridge State (SasBridge → UI) ──────────────────────────────────────────

/**
 * State of the SAS bridge, exposed as StateFlow to the UI layer.
 * Drives terminal view updates and user interaction.
 */
sealed class BridgeState {
    /** No active operation. Ready for new commands. */
    data object Idle : BridgeState()

    /** Executing a tool command. UI should show spinner. */
    data class Processing(
        val command: ToolCommand,
        val message: String = "Executing ${command.tool.toolName}..."
    ) : BridgeState()

    /** Waiting for user to approve/reject a destructive operation. */
    data class WaitingApproval(
        val command: ToolCommand,
        val description: String,
        val preview: String? = null
    ) : BridgeState()

    /** Agent loop is running — generating + executing in a cycle. */
    data class AgentRunning(
        val currentRound: Int,
        val maxRounds: Int,
        val lastToolName: String? = null
    ) : BridgeState()

    /** An error occurred during execution. */
    data class Error(
        val code: String,
        val message: String,
        val retryCommand: ToolCommand? = null
    ) : BridgeState()
}

